/**
 * mg64-policy: tool-call guard for the Mario Golf 64 decomp repo.
 *
 * Enforces:
 * - bash: no `git commit --no-verify`; no direct `make`; no direct `python3 -m splat split`;
 *   no `ctx.c` / `temp.c` mentions; no shell mutation of `asm/`; no shell writes into vendored
 *   tools (`tools/gcc_kmc`, `tools/kmc-cc`, `tools/decomp-permuter`, `tools/asm-differ`); every
 *   permuter run (`tools/permuter`, `tools/decomp-permuter/permuter.py`) must sit under a
 *   `timeout` that ends at least 120s before `NIGEL_TIMEOUT_DEADLINE_UNIX`. A permuter path that
 *   is an argument of a read-only command (`cat`, `sed`, `grep`, `git`, ...) is not a run.
 * - read: no `ctx.c` / `temp.c`. Selectors (`:10-20`, `:raw`, `:table`) are stripped first.
 * - write / edit / ast_edit (`write xd://ast_edit`): no `ctx.c`, `temp.c`, `mariogolf64.sha1`;
 *   no paths with an `asm` directory component; no vendored-tool paths. Edit targets come from
 *   `path`, `_path`, `paths`, hashline `[PATH#TAG]` / `¶PATH#TAG` headers, `MV DEST` lines, and
 *   `*** Add|Update|Delete File:` / `*** Move to:` lines.
 * - Paths inside the repo are resolved against the call's cwd, symlinks followed where they
 *   exist. Paths outside the repo and `scheme://` URLs get only the suffix rules.
 *
 * Discovery: omp loads hooks from `<session cwd>/.omp/hooks/pre/`. Decomp environments
 * (`nonmatchings/<fn>/`) reach this file through a `.omp` symlink to the repo's `.omp`. The
 * repo root is `../../..` from the realpath of this file, so it is the same either way.
 *
 * Deliberate deviations from the shell hooks (each closes a gap in them):
 * - `&` is a segment boundary for the permuter check, as are `;`, `&&`, `||`, `|`.
 * - Every permuter invocation in a command is checked, not only the first.
 *
 * Known limits:
 * - bash rules are textual. The `cwd` param on bash calls is not applied to command heuristics.
 * - `ast_edit` glob entries are checked by their literal prefix and by suffix on the whole
 *   pattern. Wildcards or braces before the first `/` (e.g. `{asm,src}/x.c`) are not expanded.
 * - The `eval` `tool.bash()` bridge emits no `tool_call`, so it is not policed.
 * - Read-only tools (`grep`, `glob`) are not policed.
 * - A bash command that mentions `permuter` but fails shell-style tokenizing (unterminated quote
 *   or trailing escape) is blocked, since its timeout cannot be checked. Commands that never
 *   mention `permuter` skip tokenizing, so heredocs with unbalanced apostrophes stay allowed.
 */
import { realpathSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import type { ExtensionAPI } from "@oh-my-pi/pi-coding-agent";

const REPO_ROOT = path.resolve(realpathSync(path.dirname(fileURLToPath(import.meta.url))), "../../..");

const MSG = {
	asmWrite:
		"Blocked: Agents must not create, edit, move, or delete files in asm/. They are generated by splat; change the corresponding C source or project metadata instead.",
	asmBash:
		"Blocked: Agents must not create, edit, move, or delete files in asm/. Read them for analysis or run the repository's build tools instead.",
	ctx: "Blocked: ctx.c is an automatically generated file for decomp.me and should be ignored.",
	temp: "Blocked: temp.c is an automatically generated file for decomp.me and should be ignored.",
	sha1: "Blocked: mariogolf64.sha1 is a reference checksum file and should not be edited.",
	vendored:
		"Blocked: do not modify the KMC toolchain (tools/gcc_kmc), tools/kmc-cc, or the vendored decomp-permuter/asm-differ submodules to change how a file compiles. If an object needs different compiler behavior, add a target-specific profile override in the Makefile's COMPILER PROFILES section instead.",
	make: "Blocked: Direct 'make' commands are not allowed. Please use the build script provided in the instructions. This will be ./tools/build-and-verify.sh to rebuild the whole project or ./build.sh <file> if you're working on a single function in a decomp environment.",
	splat:
		"Blocked: Direct 'python3 -m splat split' commands are not allowed. This command is automatically run by the build scripts when needed. Use ./tools/build-and-verify.sh to build the project properly.",
	permuterNoTimeout:
		"Blocked: permuter runs must be wrapped with a valid shell timeout, e.g. timeout 300s ./tools/permuter --source-file ...",
	permuterBadDeadline: "Blocked: NIGEL_TIMEOUT_DEADLINE_UNIX is set but is not a valid Unix timestamp.",
	permuterParse:
		"Blocked: unable to parse command while checking permuter timeout: unterminated quote or trailing escape.",
	astParse: "Blocked: unable to parse ast_edit payload while checking its paths.",
} as const;

// ---------------------------------------------------------------------------
// bash
// ---------------------------------------------------------------------------

const NO_VERIFY = /git\s+commit\s+--no-verify/i;
const MAKE = /(^|[;&|]\s*)make(\s|$)/i;
const SPLAT_SPLIT = /(^|[;&|]\s*)python3?\s+-m\s+splat\s+split(\s|$)/i;
const CTX_MENTION = /ctx\.c/;
const TEMP_MENTION = /temp\.c/;

// Shell heuristics for mutating `asm/`. Ported from block-asm-edits.sh; applied per line like grep.
const ASM_TOKEN = /(^|[\s"'=/>])asm\//;
const ASM_MUTATIONS: readonly RegExp[] = [
	/(^|[;&|\s])(tee(\s+-[^\s]+)*|touch|truncate|rm|unlink|mv|cp|install|chmod|chown|sed\s+-[^\s]*i|perl\s+-[^\s]*i)(\s[^;&|]*)?(^|[\s"'=/>])asm\//,
	/[0-9]*>{1,2}\s*(\.\/)?asm\//,
];
const APPLY_PATCH = /(^|[;&|\s])apply_patch(\s|$)/;
const GIT_TREE_WRITE = /(^|[;&|\s])git\s+(checkout|restore|clean|apply)(\s[^;&|]*)?(^|[\s"'=/>])asm\//;
const SCRIPT_RUN = /(^|[;&|\s])(python3?|ruby|node)\s+(-c|-e)(\s|$)/;
const ASM_SCRIPT_WRITE = /(^|[\s"'=/>])asm\/.*(write|unlink|remove|rename|replace|open\([^)]*,\s*["']?[wax+])/;

const VENDORED_BASH =
	/(>|>>|tee |sed -i|perl -[0-9A-Za-z]*i|apply_patch|rm |mv |cp |chmod |git checkout|git restore).*(tools\/gcc_kmc|tools\/kmc-cc|tools\/decomp-permuter|tools\/asm-differ)/;

function asmMutation(line: string): boolean {
	if (ASM_MUTATIONS.some(re => re.test(line))) return true;
	if (APPLY_PATCH.test(line) && ASM_TOKEN.test(line)) return true;
	if (GIT_TREE_WRITE.test(line)) return true;
	return SCRIPT_RUN.test(line) && ASM_SCRIPT_WRITE.test(line);
}

function bashReason(command: string): string | undefined {
	if (command === "") return undefined;
	const lines = command.split("\n");
	const anyLine = (re: RegExp) => lines.some(line => re.test(line));
	if (anyLine(NO_VERIFY)) {
		return `Blocked command: matches denied pattern '${NO_VERIFY.source}'. Use a safer alternative or explain why it's necessary.`;
	}
	if (anyLine(MAKE)) return MSG.make;
	if (anyLine(SPLAT_SPLIT)) return MSG.splat;
	if (CTX_MENTION.test(command)) return MSG.ctx;
	if (TEMP_MENTION.test(command)) return MSG.temp;
	if (lines.some(asmMutation)) return MSG.asmBash;
	if (anyLine(VENDORED_BASH)) return MSG.vendored;
	return permuterReason(command);
}

// ---------------------------------------------------------------------------
// Permuter timeout. Tokenizer is a POSIX shlex-style splitter that also splits on ; & |.
// ---------------------------------------------------------------------------

const RESERVED_SECONDS = 120;
const PERMUTER_PATHS: Record<string, true> = { "tools/permuter": true, "tools/decomp-permuter/permuter.py": true };
const TIMEOUT_NO_ARG: Record<string, true> = { "--foreground": true, "--preserve-status": true, "-v": true };
const TIMEOUT_ONE_ARG: Record<string, true> = { "-k": true, "--kill-after": true, "-s": true, "--signal": true };
const ASSIGNMENT = /^[A-Za-z_][A-Za-z0-9_]*=/;
const DURATION = /^([0-9]+(?:\.[0-9]+)?)([smhd]?)$/;
const UNIT_SECONDS: Record<string, number> = { "": 1, s: 1, m: 60, h: 3600, d: 86400 };
const SHELL_OPERATOR_CHARS = ";&|";

/** Returns null on unterminated quotes or a trailing escape. Newlines act as `;`. */
function tokenize(input: string): string[] | null {
	const command = input.replaceAll("\n", ";");
	const tokens: string[] = [];
	let token = "";
	let started = false;
	const flush = () => {
		if (started) tokens.push(token);
		token = "";
		started = false;
	};
	let i = 0;
	while (i < command.length) {
		const ch = command[i];
		if (ch === "'") {
			const end = command.indexOf("'", i + 1);
			if (end === -1) return null;
			started = true;
			token += command.slice(i + 1, end);
			i = end + 1;
		} else if (ch === '"') {
			started = true;
			i++;
			let closed = false;
			while (i < command.length) {
				const c = command[i];
				if (c === '"') {
					closed = true;
					i++;
					break;
				}
				if (c === "\\") {
					const next = command[i + 1];
					if (next === undefined) return null;
					token += next === '"' || next === "\\" ? next : `\\${next}`;
					i += 2;
					continue;
				}
				token += c;
				i++;
			}
			if (!closed) return null;
		} else if (ch === "\\") {
			const next = command[i + 1];
			if (next === undefined) return null;
			started = true;
			token += next;
			i += 2;
		} else if (ch === " " || ch === "\t" || ch === "\r") {
			flush();
			i++;
		} else if (SHELL_OPERATOR_CHARS.includes(ch)) {
			flush();
			let j = i;
			while (j < command.length && SHELL_OPERATOR_CHARS.includes(command[j])) j++;
			tokens.push(command.slice(i, j));
			i = j;
		} else {
			started = true;
			token += ch;
			i++;
		}
	}
	flush();
	return tokens;
}

function isPermuterToken(token: string): boolean {
	return PERMUTER_PATHS[token.replace(/^[./]+/, "")] === true;
}

function isSegmentBoundary(token: string): boolean {
	return /^[;&|]+$/.test(token);
}

/** Commands that only inspect their path arguments; a permuter path after one of them is not a run. */
const READ_ONLY_COMMANDS: Record<string, true> = {
	cat: true,
	diff: true,
	file: true,
	git: true,
	grep: true,
	head: true,
	less: true,
	ls: true,
	readlink: true,
	realpath: true,
	rg: true,
	sed: true,
	stat: true,
	tail: true,
	wc: true,
};

/** First token of the segment after leading `VAR=value` assignments. */
function commandWord(tokens: string[], start: number, end: number): string | undefined {
	let i = start;
	while (i < end && ASSIGNMENT.test(tokens[i])) i++;
	return i < end ? tokens[i] : undefined;
}

function segmentStart(tokens: string[], index: number): number {
	for (let i = index - 1; i >= 0; i--) {
		if (isSegmentBoundary(tokens[i])) return i + 1;
	}
	return 0;
}

function parseDuration(token: string): number | undefined {
	const match = DURATION.exec(token);
	if (match === null) return undefined;
	const seconds = Math.floor(Number(match[1]) * UNIT_SECONDS[match[2]]);
	return seconds > 0 ? seconds : undefined;
}

/** Duration of the `timeout` wrapper covering tokens[start, end), or undefined if none. */
function timeoutSeconds(tokens: string[], start: number, end: number): number | undefined {
	let i = start;
	while (i < end && ASSIGNMENT.test(tokens[i])) i++;
	if (i >= end || tokens[i] !== "timeout") return undefined;
	for (i++; i < end; i++) {
		const token = tokens[i];
		if (TIMEOUT_NO_ARG[token] === true) continue;
		if (TIMEOUT_ONE_ARG[token] === true) {
			i++;
			continue;
		}
		if (token.startsWith("--kill-after=") || token.startsWith("--signal=")) continue;
		if (token.startsWith("-") && token !== "-") continue;
		return parseDuration(token);
	}
	return undefined;
}

function permuterDeadlineReason(seconds: number): string | undefined {
	const raw = process.env.NIGEL_TIMEOUT_DEADLINE_UNIX ?? "";
	if (raw === "") return undefined;
	if (!/^\s*[+-]?\d+\s*$/.test(raw)) return MSG.permuterBadDeadline;
	const latestFinish = Number(raw) - RESERVED_SECONDS;
	const now = Math.trunc(Date.now() / 1000);
	if (now + seconds <= latestFinish) return undefined;
	const allowed = latestFinish - now;
	const limit = allowed > 0 ? `Use timeout no greater than ${allowed}s.` : "Skip the run.";
	return `Blocked: permuter timeout would leave less than ${RESERVED_SECONDS} seconds before NIGEL_TIMEOUT_DEADLINE_UNIX. ${limit}`;
}

function permuterReason(command: string): string | undefined {
	if (!command.includes("permuter")) return undefined;
	const tokens = tokenize(command);
	if (tokens === null) return MSG.permuterParse;
	for (let index = 0; index < tokens.length; index++) {
		if (!isPermuterToken(tokens[index])) continue;
		const start = segmentStart(tokens, index);
		const command = commandWord(tokens, start, index);
		if (command !== undefined && READ_ONLY_COMMANDS[command] === true) continue;
		const seconds = timeoutSeconds(tokens, start, index);
		if (seconds === undefined) return MSG.permuterNoTimeout;
		const reason = permuterDeadlineReason(seconds);
		if (reason !== undefined) return reason;
	}
	return undefined;
}

// ---------------------------------------------------------------------------
// Paths
// ---------------------------------------------------------------------------

const VENDORED_PATHS = ["tools/gcc_kmc", "tools/decomp-permuter", "tools/asm-differ", "tools/kmc-cc"];
const INTERNAL_URL = /^[A-Za-z][A-Za-z0-9+.-]*:\/\//;
const GLOB_META = /[*?[{]/;

function isInternalUrl(target: string): boolean {
	return INTERNAL_URL.test(target) && !target.startsWith("file://");
}

/** realpath, falling back to the nearest existing ancestor for paths that do not exist yet. */
function realpathLenient(target: string): string {
	try {
		return realpathSync(target);
	} catch {
		const parent = path.dirname(target);
		return parent === target ? target : path.join(realpathLenient(parent), path.basename(target));
	}
}

function resolveToolPath(raw: string, cwd: string): string {
	let target = raw;
	if (target.startsWith("file://")) target = target.slice("file://".length);
	else if (target === "~" || target.startsWith("~/")) target = path.join(homedir(), target.slice(1));
	return realpathLenient(path.resolve(cwd, target));
}

/** Repo-relative POSIX path, or undefined when outside the repo. */
function repoRelative(resolved: string): string | undefined {
	const rel = path.relative(REPO_ROOT, resolved);
	const segments = rel.split(path.sep);
	if (path.isAbsolute(rel) || segments[0] === "..") return undefined;
	return segments.join("/");
}

function isVendored(rel: string): boolean {
	return VENDORED_PATHS.some(p => rel === p || rel.startsWith(`${p}/`));
}

/** Suffix and path rules for anything the agent may create or change. */
function writeReason(raw: string, cwd: string): string | undefined {
	const resolved = isInternalUrl(raw) ? undefined : resolveToolPath(raw, cwd);
	const names = resolved === undefined ? [raw] : [raw, resolved];
	if (names.some(n => n.endsWith("ctx.c"))) return MSG.ctx;
	if (names.some(n => n.endsWith("temp.c"))) return MSG.temp;
	const rel = resolved === undefined ? undefined : repoRelative(resolved);
	if (rel !== undefined) {
		if (rel.split("/").includes("asm")) return MSG.asmWrite;
		if (isVendored(rel)) return MSG.vendored;
	}
	if (names.some(n => n.endsWith("mariogolf64.sha1"))) return MSG.sha1;
	return undefined;
}

/** `read` selectors: `file.c:10-20`, `file.c:raw:2-4`, `db.sqlite:table`. Each prefix is a candidate. */
function selectorCandidates(raw: string): string[] {
	const candidates = [raw];
	let head = raw;
	for (let cut = head.lastIndexOf(":"); cut > 0; cut = head.lastIndexOf(":")) {
		head = head.slice(0, cut);
		candidates.push(head);
	}
	return candidates;
}

/** `read` gets only the suffix rules. */
function readReason(raw: string, cwd: string): string | undefined {
	for (const candidate of selectorCandidates(raw)) {
		const resolved = isInternalUrl(candidate) ? undefined : resolveToolPath(candidate, cwd);
		const names = resolved === undefined ? [candidate] : [candidate, resolved];
		if (names.some(n => n.endsWith("ctx.c"))) return MSG.ctx;
		if (names.some(n => n.endsWith("temp.c"))) return MSG.temp;
	}
	return undefined;
}

/** `ast_edit` entries may be globs. Path rules see the literal prefix; suffix rules see the whole pattern. */
function astEntryReason(entry: string, cwd: string): string | undefined {
	const meta = GLOB_META.exec(entry);
	if (meta === null) return writeReason(entry, cwd);
	return writeReason(entry.slice(0, meta.index), cwd) ?? writeReason(entry, cwd);
}

// ---------------------------------------------------------------------------
// Edit targets (hashline, legacy hashline, MV, apply_patch markers)
// ---------------------------------------------------------------------------

const HASHLINE_TAG = /#[0-9a-fA-F]{4}$/;
const LEGACY_HEADER_PREFIX = "¶";
const HASHLINE_MV = /^\s*MV\s+(.+)$/;
const APPLY_PATCH_FILE = /^\*\*\* (?:Add|Update|Delete) File: (.+)$/;
const APPLY_PATCH_MOVE = /^\*\*\* Move to: (.+)$/;

function normalizeHeaderPath(body: string): string | undefined {
	const trimmed = body.trim();
	const tag = HASHLINE_TAG.exec(trimmed);
	const rawPath = (tag === null ? trimmed : trimmed.slice(0, tag.index)).trim();
	if (rawPath === "") return undefined;
	const quote = rawPath[0];
	if ((quote === '"' || quote === "'") && rawPath.length >= 2 && rawPath.endsWith(quote)) {
		return rawPath.slice(1, -1);
	}
	return rawPath;
}

function patchTargets(text: string): string[] {
	const targets: string[] = [];
	const body = text.startsWith("\uFEFF") ? text.slice(1) : text;
	for (const rawLine of body.split("\n")) {
		const line = rawLine.replace(/\r$/, "");
		let header: string | undefined;
		if (line.startsWith("[") && line.endsWith("]")) {
			header = line.slice(1, -1);
		} else {
			const legacy = line.trimStart();
			if (legacy.startsWith(LEGACY_HEADER_PREFIX)) header = legacy.replace(/^¶+/, "");
		}
		const candidates = [
			header,
			HASHLINE_MV.exec(line)?.[1],
			APPLY_PATCH_FILE.exec(line)?.[1],
			APPLY_PATCH_MOVE.exec(line)?.[1],
		];
		for (const candidate of candidates) {
			if (candidate === undefined) continue;
			const target = normalizeHeaderPath(candidate);
			if (target !== undefined) targets.push(target);
		}
	}
	return targets;
}

function editTargets(input: Record<string, unknown>): string[] {
	const targets = fieldStrings(input, ["path", "_path"]);
	if (Array.isArray(input.paths)) targets.push(...input.paths.filter(isNonEmptyString));
	for (const text of fieldStrings(input, ["input", "_input"])) targets.push(...patchTargets(text));
	return targets;
}

/** `ast_edit` payload entries from `path` and `paths`. */
function payloadEntries(input: Record<string, unknown>): string[] {
	const entries = fieldStrings(input, ["path"]);
	const paths = input.paths;
	for (const entry of Array.isArray(paths) ? paths : [paths]) {
		if (isNonEmptyString(entry)) entries.push(entry);
	}
	return entries;
}

// ---------------------------------------------------------------------------
// Dispatch
// ---------------------------------------------------------------------------

function asRecord(value: unknown): Record<string, unknown> {
	return typeof value === "object" && value !== null && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
}

function isNonEmptyString(value: unknown): value is string {
	return typeof value === "string" && value.length > 0;
}

function fieldStrings(input: Record<string, unknown>, keys: readonly string[]): string[] {
	const values: string[] = [];
	for (const key of keys) {
		const value = input[key];
		if (isNonEmptyString(value)) values.push(value);
	}
	return values;
}

function firstReason<T>(items: readonly T[], check: (item: T) => string | undefined): string | undefined {
	for (const item of items) {
		const reason = check(item);
		if (reason !== undefined) return reason;
	}
	return undefined;
}

function astEntriesReason(entries: readonly string[], cwd: string): string | undefined {
	return firstReason(entries, entry => astEntryReason(entry, cwd));
}

function astPayloadReason(content: string, cwd: string): string | undefined {
	let payload: unknown;
	try {
		payload = JSON.parse(content);
	} catch {
		return MSG.astParse;
	}
	return astEntriesReason(payloadEntries(asRecord(payload)), cwd);
}

function decide(toolName: string, input: Record<string, unknown>, cwd: string): string | undefined {
	switch (toolName) {
		case "bash":
			return typeof input.command === "string" ? bashReason(input.command) : undefined;
		case "read":
			return firstReason(fieldStrings(input, ["path", "_path"]), target => readReason(target, cwd));
		case "write": {
			const content = typeof input.content === "string" ? input.content : "";
			return firstReason(fieldStrings(input, ["path", "_path"]), target =>
				target.startsWith("xd://ast_edit") ? astPayloadReason(content, cwd) : writeReason(target, cwd),
			);
		}
		case "edit":
			return firstReason(editTargets(input), target => writeReason(target, cwd));
		case "ast_edit":
			return astEntriesReason(payloadEntries(input), cwd);
		default:
			return undefined;
	}
}

export default function mg64Policy(pi: ExtensionAPI): void {
	pi.on("tool_call", async (event, ctx) => {
		const reason = decide(event.toolName, asRecord(event.input), ctx.cwd);
		return reason === undefined ? undefined : { block: true, reason };
	});
}
