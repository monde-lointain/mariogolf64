#!/usr/bin/env python3
"""Turn splat's output for a hand-written assembly file into source form.

    clean_hasm.py FILE.s [OLD_LABEL=NEW_LABEL ...]

Drops the ROM offset and encoding comments and the `nonmatching` size
markers, which splat adds to every function, and renames the local labels
given on the command line (unnamed ones keep their .L<address> names, so
the output still assembles). FILE.s is rewritten in place; the comments
that say why the code is written as it is still have to be added by hand.
"""

import re
import sys

INSN_RE = re.compile(r"^\s*/\* [0-9A-F]+ [0-9A-F]+ [0-9A-F]{8} \*/  (.*)$")
SPLAT_LINE_RE = re.compile(r"^(nonmatching \w+, 0x[0-9A-F]+|/\* Generated by spimdisasm .* \*/)$")


def clean(text, renames):
    lines = []
    for line in text.splitlines():
        if SPLAT_LINE_RE.match(line):
            continue
        match = INSN_RE.match(line)
        if match:
            # Delay slots keep their one-space indent from splat
            line = "    " + re.sub(r"(\S+) +", r"\1 ", match.group(1), count=1)
        lines.append(line.rstrip())
    result = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)) + "\n"
    for old, new in renames.items():
        result = re.sub(re.escape(old) + r"\b", new, result)
    return result


def main():
    path = sys.argv[1]
    renames = dict(arg.split("=", 1) for arg in sys.argv[2:])
    with open(path) as asm_file:
        text = asm_file.read()
    with open(path, "w") as asm_file:
        asm_file.write(clean(text, renames))


if __name__ == "__main__":
    main()
