#!/usr/bin/env bash
set -euo pipefail

# stdin: JSON with tool_input containing .file_path for Write/Edit tools,
# patch text for apply_patch, or .command/.cmd for shell tools.
input=$(cat)

# Generated splat output lives under asm/. Hand-written assembly sources
# (src/libultra/**/*.s, src/libkmc/*.s, src/entry/entry.s) are project source
# and stay editable, e.g. for the match-ultralib-segment workflow.
is_generated_asm_path() {
  case "$1" in
    asm/*|./asm/*|*/asm/*) return 0 ;;
  esac
  return 1
}

is_blocked_path() {
  local file_path="$1"

  if is_generated_asm_path "$file_path"; then
    echo "Blocked: Agents must not create, edit, move, or delete files in asm/. They are generated by splat; change the corresponding C source or project metadata instead." 1>&2
    exit 2
  fi
}

# Check for direct file path fields in Write/Edit-style tools.
while IFS= read -r file_path; do
  [[ -n "$file_path" ]] && is_blocked_path "$file_path"
done < <(echo "$input" | jq -r '.tool_input.file_path?, .tool_input.path? // empty')

# Check apply_patch-style freeform patch bodies.
patch_text=$(echo "$input" | jq -r '
  if (.tool_input | type) == "string" then
    .tool_input
  else
    .tool_input.patch? // .tool_input.input? // empty
  end
')

while IFS= read -r file_path; do
  [[ -n "$file_path" ]] && is_blocked_path "$file_path"
done < <(
  printf '%s\n' "$patch_text" |
    sed -n \
      -e 's/^\*\*\* Add File: //p' \
      -e 's/^\*\*\* Delete File: //p' \
      -e 's/^\*\*\* Update File: //p' \
      -e 's/^\*\*\* Move to: //p' \
      -e 's/^--- a\///p' \
      -e 's/^+++ b\///p'
)

# Block shell mutation primitives when they target an explicit asm/ path.
# Read-only commands that inspect assembly remain allowed, as do build scripts
# that regenerate asm/ without naming those outputs here.
command=$(echo "$input" | jq -r '.tool_input.command? // .tool_input.cmd? // empty')

if [[ -n "$command" ]]; then
  # An asm/ path token: start of a word, a quote, '=', or a path separator.
  asm_path='(^|[[:space:]"'\''=/>])asm/'
  if {
    printf '%s\n' "$command" | grep -Eq \
      "(^|[;&|[:space:]])(tee([[:space:]]+-[^[:space:]]+)*|touch|truncate|rm|unlink|mv|cp|install|chmod|chown|sed[[:space:]]+-[^[:space:]]*i|perl[[:space:]]+-[^[:space:]]*i)([[:space:]][^;&|]*)?${asm_path}" ||
    printf '%s\n' "$command" | grep -Eq '[0-9]*>{1,2}[[:space:]]*(\./)?asm/' ||
    { printf '%s\n' "$command" | grep -Eq '(^|[;&|[:space:]])apply_patch([[:space:]]|$)' &&
      printf '%s\n' "$command" | grep -Eq "$asm_path"; } ||
    printf '%s\n' "$command" | grep -Eq \
      "(^|[;&|[:space:]])git[[:space:]]+(checkout|restore|clean|apply)([[:space:]][^;&|]*)?${asm_path}" ||
    { printf '%s\n' "$command" | grep -Eq '(^|[;&|[:space:]])(python3?|ruby|node)[[:space:]]+(-c|-e)([[:space:]]|$)' &&
      printf '%s\n' "$command" | grep -Eq "${asm_path}.*(write|unlink|remove|rename|replace|open\\([^)]*,[[:space:]]*[\"']?[wax+])"; }
  }; then
    echo "Blocked: Agents must not create, edit, move, or delete files in asm/. Read them for analysis or run the repository's build tools instead." 1>&2
    exit 2
  fi
fi

exit 0
